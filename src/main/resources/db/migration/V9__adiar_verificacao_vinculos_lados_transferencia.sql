-- Uma Transferencia e seus dois lados mudam de conta na mesma transacao: cada FK composta
-- depende de uma linha que a outra tabela ainda referencia com a conta anterior. A verificacao
-- passa a ocorrer no commit, quando as duas tabelas ja estao na forma final.
ALTER TABLE TB007_TRANSFERENCIA DROP CONSTRAINT FK007_04_TRANSACAO_SAIDA;
ALTER TABLE TB007_TRANSFERENCIA
    ADD CONSTRAINT FK007_04_TRANSACAO_SAIDA FOREIGN KEY (ID_TRANSACAO_SAIDA, ID_USUARIO, ID_CONTA_ORIGEM)
        REFERENCES TB006_TRANSACAO (ID_REGISTRO, ID_USUARIO, ID_CONTA_FINANCEIRA)
        ON DELETE RESTRICT
        DEFERRABLE INITIALLY DEFERRED;

ALTER TABLE TB007_TRANSFERENCIA DROP CONSTRAINT FK007_05_TRANSACAO_ENTRADA;
ALTER TABLE TB007_TRANSFERENCIA
    ADD CONSTRAINT FK007_05_TRANSACAO_ENTRADA FOREIGN KEY (ID_TRANSACAO_ENTRADA, ID_USUARIO, ID_CONTA_DESTINO)
        REFERENCES TB006_TRANSACAO (ID_REGISTRO, ID_USUARIO, ID_CONTA_FINANCEIRA)
        ON DELETE RESTRICT
        DEFERRABLE INITIALLY DEFERRED;

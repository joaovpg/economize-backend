-- Ocorrência de série desligada da série como transação simples: preserva a origem
-- (segmento, data original e número da parcela) sem vincular a transação à série.

ALTER TABLE TB005_SEGMENTO_RECORRENCIA
    ADD CONSTRAINT UK005_02_ID_USUARIO UNIQUE (ID_REGISTRO, ID_USUARIO);

ALTER TABLE TB006_TRANSACAO
    ADD COLUMN ID_SEGMENTO_ORIGEM UUID,
    ADD COLUMN DAT_ORIGEM_RECORRENCIA DATE,
    ADD COLUMN INT_NUMERO_PARCELA_ORIGEM INTEGER,
    ADD CONSTRAINT FK006_06_SEGMENTO_ORIGEM FOREIGN KEY (ID_SEGMENTO_ORIGEM, ID_USUARIO)
        REFERENCES TB005_SEGMENTO_RECORRENCIA (ID_REGISTRO, ID_USUARIO) ON DELETE RESTRICT,
    ADD CONSTRAINT CK006_07_ORIGEM_RECORRENCIA CHECK (
        (
            ID_SEGMENTO_ORIGEM IS NULL
            AND DAT_ORIGEM_RECORRENCIA IS NULL
            AND INT_NUMERO_PARCELA_ORIGEM IS NULL
        )
        OR (
            ID_SEGMENTO_ORIGEM IS NOT NULL
            AND DAT_ORIGEM_RECORRENCIA IS NOT NULL
            AND NOT BOL_EXCECAO_RECORRENCIA
            AND ID_GRUPO_RECORRENCIA IS NULL
            AND ID_SEGMENTO_RECORRENCIA IS NULL
            AND DAT_IDENTIFICADOR_RECORRENCIA IS NULL
        )
    ),
    ADD CONSTRAINT CK006_08_NUMERO_PARCELA_ORIGEM CHECK (
        INT_NUMERO_PARCELA_ORIGEM IS NULL OR INT_NUMERO_PARCELA_ORIGEM > 0
    );

-- Cada ocorrência de série só pode ser desligada uma vez.
CREATE UNIQUE INDEX UK006_03_ORIGEM_RECORRENCIA
    ON TB006_TRANSACAO (ID_SEGMENTO_ORIGEM, DAT_ORIGEM_RECORRENCIA)
    WHERE ID_SEGMENTO_ORIGEM IS NOT NULL;

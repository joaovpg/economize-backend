ALTER TABLE TB005_SEGMENTO_RECORRENCIA
    ADD COLUMN STR_POLITICA_DATA VARCHAR(30);

UPDATE TB005_SEGMENTO_RECORRENCIA SEGMENTO
SET STR_POLITICA_DATA = CASE
    WHEN GRUPO.STR_TIPO = 'PARCELAMENTO' THEN 'AJUSTAR_ULTIMO_DIA_MES'
    ELSE 'PADRAO'
END
FROM TB004_GRUPO_RECORRENCIA GRUPO
WHERE GRUPO.ID_REGISTRO = SEGMENTO.ID_GRUPO_RECORRENCIA
  AND GRUPO.ID_USUARIO = SEGMENTO.ID_USUARIO;

